def test_build_sigterm_reaps_child_and_cleans_temporary_output(tmp_path: Path) -> None:
    # given
    fake_go = tmp_path / "go"
    child_pid = tmp_path / "child.pid"
    temporary_parent = tmp_path / "temporary"
    temporary_parent.mkdir()
    fake_go.write_text(
        "#!/bin/sh\n"
        f"echo $$ > {child_pid}\n"
        "trap 'exit 143' TERM INT HUP\n"
        "while :; do sleep 1; done\n",
        encoding="utf-8",
    )
    fake_go.chmod(0o755)
    environment = {
        **os.environ,
        "MODULE_ROOT": str(tmp_path),
        "GO": str(fake_go),
        "TMPDIR": str(temporary_parent),
    }
    process = subprocess.Popen(
        [sys.executable, str(Path(module_tooling.__file__)), "build"],
        env=environment,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    deadline = time.monotonic() + 5
    while not child_pid.is_file() and time.monotonic() < deadline:
        time.sleep(0.02)
    assert child_pid.is_file()

    # when
    process.send_signal(signal.SIGTERM)
    _, stderr = process.communicate(timeout=15)

    # then
    assert process.returncode == 143, stderr
    pid = int(child_pid.read_text(encoding="utf-8"))
    with pytest.raises(ProcessLookupError):
        os.kill(pid, 0)
    assert list(temporary_parent.iterdir()) == []
