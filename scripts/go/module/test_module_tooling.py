def make_fixture(tmp_path: Path, tooling: Path) -> Path:
    fixture = tmp_path / "orders-service"
    fixture.mkdir()
    (fixture / "go.mod").write_text(
        "module example.test/orders-service\n\ngo 1.27.2\n", encoding="utf-8"
    )
    (fixture / "service.go").write_text(
        "package orders\n\nfunc Available() bool { return true }\n", encoding="utf-8"
    )
    (fixture / "service_test.go").write_text(
        'package orders\n\nimport "testing"\n\n'
        'func TestAvailable(t *testing.T) { if !Available() { t.Fatal("unavailable") } }\n',
        encoding="utf-8",
    )
    (fixture / "Makefile").write_text(
        "GO ?= go\n"
        "BUF_VERSION := unused\n"
        "PROTOC_GEN_GO_VERSION := unused\n"
        "PROTOC_GEN_GO_GRPC_VERSION := unused\n"
        "GOLANGCI_LINT_VERSION := unused\n"
        "GOVULNCHECK_VERSION := unused\n"
        f"COMMON_GO_TOOLING_DIR := {tooling}\n"
        "include $(COMMON_GO_TOOLING_DIR)/common.mk\n",
        encoding="utf-8",
    )
    return fixture


@pytest.mark.integration
def test_real_make_coverage_interface(tmp_path: Path) -> None:
    # given
    tooling = Path(module_tooling.__file__).resolve().parent
    fixture = make_fixture(tmp_path, tooling)
    environment = {**os.environ, "PYTHON": os.environ.get("PYTHON", os.sys.executable)}

    # when
    result = subprocess.run(
        [
            "make",
            "--no-print-directory",
            "-C",
            str(fixture),
            "coverage-check",
            "COVERAGE_FILE=reports/coverage.out",
        ],
        check=False,
        text=True,
        capture_output=True,
        timeout=180,
        env=environment,
    )

    # then
    assert result.returncode == 0, result.stderr
    assert (
        (fixture / "reports" / "coverage.out")
        .read_text(encoding="utf-8")
        .startswith("mode: atomic")
    )


@pytest.mark.parametrize(
    ("fake_body", "message"),
    [("exit 7", "failed with status 7"), ("exit 0", "expected executable server")],
)
def test_build_reports_failed_or_missing_binary(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, fake_body: str, message: str
) -> None:
    # given
    fake_go = tmp_path / "go"
    fake_go.write_text(f"#!/bin/sh\n{fake_body}\n", encoding="utf-8")
    fake_go.chmod(0o755)
    monkeypatch.setenv("MODULE_ROOT", str(tmp_path))
    monkeypatch.setenv("GO", str(fake_go))

    # when / then
    with pytest.raises(module_tooling.ToolingError, match=message):
        module_tooling.build_command(object())


