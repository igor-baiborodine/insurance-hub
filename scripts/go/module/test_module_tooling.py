def write_profile(path: Path, entries: list[str]) -> None:
    path.write_text("mode: atomic\n" + "\n".join(entries) + "\n", encoding="utf-8")


def test_coverage_counts_statements_and_applies_exclusions(tmp_path: Path) -> None:
    # given
    profile = tmp_path / "coverage.out"
    write_profile(
        profile,
        [
            "example.test/orders/service.go:1.1,1.2 3 1",
            "example.test/orders/service.go:2.1,2.2 1 0",
            "example.test/orders/generated/service.pb.go:1.1,1.2 100 0",
        ],
    )

    # when
    covered, total = module_tooling.parse_coverage(
        profile, 75, "example.test/orders", ["generated"]
    )

    # then
    assert (covered, total) == (3, 4)


