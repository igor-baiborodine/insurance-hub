"""Tests for deterministic configured Dockerfile generation."""

from __future__ import annotations

import stat
from dataclasses import replace
from pathlib import Path

import pytest

from scripts.go.service import dockerfile
from scripts.go.service.tooling_config import load_tooling_config

REPOSITORY_ROOT = Path(__file__).resolve().parents[3]
CONFIG_PATH = REPOSITORY_ROOT / "templates/go-service/go-service-tooling.json"
CURRENT_DOCKERFILE_CONFIG_PATH = (
    REPOSITORY_ROOT / "services/policy-search-service/go-service-tooling.json"
)


def test_render_is_deterministic_and_matches_current_service() -> None:
    # given
    config = load_tooling_config(CURRENT_DOCKERFILE_CONFIG_PATH)

    # when
    first = dockerfile.render(config)
    second = dockerfile.render(config)

    # then
    assert first == second
    assert first == (config.module_root / "Dockerfile").read_text(encoding="utf-8")
    assert first.startswith("# Code generated by scripts/go/service/dockerfile.py")


def test_check_reports_drift_without_mutating(tmp_path: Path) -> None:
    # given
    source = load_tooling_config(CONFIG_PATH)
    config = replace(source, module_root=tmp_path)
    output = tmp_path / "Dockerfile"
    original = dockerfile.render(config)
    output.write_text(original + "# drift\n", encoding="utf-8")

    # when / then
    with pytest.raises(dockerfile.DockerfileError, match="generated Dockerfile differs"):
        dockerfile.check(config)

    # then
    assert output.read_text(encoding="utf-8") == original + "# drift\n"


def test_generate_does_not_replace_output_when_render_fails(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    # given
    source = load_tooling_config(CONFIG_PATH)
    config = replace(source, module_root=tmp_path)
    output = tmp_path / "Dockerfile"
    original = dockerfile.render(config)
    output.write_text(original, encoding="utf-8")
    monkeypatch.setattr(
        dockerfile,
        "render",
        lambda _config: (_ for _ in ()).throw(dockerfile.DockerfileError("controlled")),
    )

    # when / then
    with pytest.raises(dockerfile.DockerfileError, match="controlled"):
        dockerfile.generate(config)

    # then
    assert output.read_text(encoding="utf-8") == original


@pytest.mark.parametrize(("existing_mode", "expected_mode"), ((None, 0o644), (0o640, 0o640)))
def test_generate_uses_source_file_permissions(
    tmp_path: Path,
    existing_mode: int | None,
    expected_mode: int,
) -> None:
    # given
    source = load_tooling_config(CONFIG_PATH)
    config = replace(source, module_root=tmp_path)
    output = tmp_path / "Dockerfile"
    if existing_mode is not None:
        output.write_text("stale\n", encoding="utf-8")
        output.chmod(existing_mode)

    # when
    dockerfile.generate(config)

    # then
    assert stat.S_IMODE(output.stat().st_mode) == expected_mode
    assert output.read_text(encoding="utf-8") == dockerfile.render(config)
